"""Render paper/generated/results_table.tex + numbers.tex from results/summary.json.

Every number in the manuscript reads from this script's output — never
hand-typed (same convention as our other papers).

Usage: python scripts/render_results.py [--results-dir results] [--out-dir paper/generated]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

STRATEGY_LABELS = {
    "none": "None (frozen)",
    "success_only": "Self: successes",
    "near_miss": "Self: near-misses",
    "success_coverage": "Self: novel successes",
    "relabel": "Oracle: relabel all",
    "relabel_curated": "Oracle: curated relabel",
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", default="results",
                    help="results dir (or parent with main/ for the main study)")
    ap.add_argument("--main-dir", default=None, help="dir with the main study summary.json")
    ap.add_argument("--vision-dir", default=None, help="dir with the vision study summary.json")
    ap.add_argument("--dqn-file", default=None, help="path to the DQN baseline json")
    ap.add_argument("--out-dir", default="paper/generated")
    args = ap.parse_args()

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    if args.main_dir:
        summary_path = Path(args.main_dir) / "summary.json"
    else:
        res_dir = Path(args.results_dir)
        summary_path = res_dir / "summary.json"
        if not summary_path.exists():
            summary_path = res_dir / "main" / "summary.json"  # study lives in results/main/
    summary = json.loads(summary_path.read_text())

    vision = None
    if args.vision_dir:
        vp = Path(args.vision_dir) / "summary.json"
        if vp.exists():
            vision = json.loads(vp.read_text())
    dqn = None
    if args.dqn_file and Path(args.dqn_file).exists():
        dqn = json.loads(Path(args.dqn_file).read_text())

    abl = None
    abl_path = res_dir / "ablations.json"
    if abl_path.exists():
        abl = json.loads(abl_path.read_text())

    strategies = summary["strategies"]
    iters = list(range(summary["config"]["iterations"] + 1))

    # ---- results table -------------------------------------------------- #
    lines = [
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Held-out push success rate (mean $\\pm$ std over "
        f"{summary['config']['seeds']} training seeds, "
        f"{summary['config']['eval_starts']} held-out starts per evaluation) "
        "by curation strategy and flywheel iteration. "
        "Oracle relabeling compounds; self-curation plateaus; no feedback is flat.}",
        "\\label{tab:results}",
        "\\small",
        "\\begin{tabular}{l" + "c" * len(iters) + "}",
        "\\toprule",
        "Strategy & " + " & ".join(f"iter. {i}" for i in iters) + " \\\\",
        "\\midrule",
    ]
    order = ["none", "success_only", "near_miss", "success_coverage",
             "relabel_curated", "relabel"]
    for name in order:
        d = strategies[name]
        cells = " & ".join(
            f"{m:.2f}$\\pm${s:.2f}" for m, s in zip(d["success_rate_mean"], d["success_rate_std"])
        )
        label = STRATEGY_LABELS.get(name, name)
        lines.append(f"{label} & {cells} \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    (out / "results_table.tex").write_text("\n".join(lines) + "\n")

    # ---- number macros --------------------------------------------------- #
    def num(name: str, i: int) -> float:
        return strategies[name]["success_rate_mean"][i]

    def num_std(name: str, i: int) -> float:
        return strategies[name]["success_rate_std"][i]

    LAST = -1  # final flywheel iteration
    base = num("none", 0)
    rel_final = num("relabel", LAST)
    cur_final = num("relabel_curated", LAST)
    so_final = num("success_only", LAST)
    nm_final = num("near_miss", LAST)
    sc_final = num("success_coverage", LAST)
    rel_gain = rel_final - num("relabel", 0)
    cur_gain = cur_final - num("relabel_curated", 0)
    so_gain = so_final - num("success_only", 0)
    nm_gain = nm_final - num("near_miss", 0)
    cov_gain = sc_final - num("success_coverage", 0)

    macros = [
        "%% AUTO-GENERATED by scripts/render_results.py -- do not edit by hand",
        f"\\newcommand{{\\baseSuccess}}{{{base:.2f}}}",
        f"\\newcommand{{\\relabelFinal}}{{{rel_final:.2f}}}",
        f"\\newcommand{{\\relabelGain}}{{{rel_gain:.2f}}}",
        f"\\newcommand{{\\curatedFinal}}{{{cur_final:.2f}}}",
        f"\\newcommand{{\\curatedGain}}{{{cur_gain:.2f}}}",
        f"\\newcommand{{\\selfFinal}}{{{so_final:.2f}}}",
        f"\\newcommand{{\\selfGain}}{{{so_gain:.2f}}}",
        f"\\newcommand{{\\nearMissFinal}}{{{nm_final:.2f}}}",
        f"\\newcommand{{\\nearMissGain}}{{{nm_gain:.2f}}}",
        f"\\newcommand{{\\coverageFinal}}{{{sc_final:.2f}}}",
        f"\\newcommand{{\\coverageGain}}{{{cov_gain:.2f}}}",
        f"\\newcommand{{\\numSeeds}}{{{summary['config']['seeds']}}}",
        f"\\newcommand{{\\numEval}}{{{summary['config']['eval_starts']}}}",
        f"\\newcommand{{\\numIter}}{{{summary['config']['iterations']}}}",
    ]
    if abl:
        oc = abl["oracle_crossover"]
        le = abl["label_efficiency"]
        df = abl["difficulty"]
        macros += [
            "%% oracle-quality ablation (results/oracle/)",
            f"\\newcommand{{\\blindClean}}{{{oc['relabel'][0]:.2f}}}",
            f"\\newcommand{{\\curatedClean}}{{{oc['relabel_curated'][0]:.2f}}}",
            f"\\newcommand{{\\blindHigh}}{{{oc['relabel'][2]:.2f}}}",
            f"\\newcommand{{\\curatedHigh}}{{{oc['relabel_curated'][2]:.2f}}}",
            f"\\newcommand{{\\blindDrop}}{{{100 * (oc['relabel'][0] - oc['relabel'][2]) / oc['relabel'][0]:.0f}}}",
            f"\\newcommand{{\\curatedDrop}}{{{100 * (oc['relabel_curated'][0] - oc['relabel_curated'][2]) / oc['relabel_curated'][0]:.0f}}}",
            "%% label-efficiency ablation (results/main/)",
            f"\\newcommand{{\\blindQueries}}{{{le['relabel']['queries'][-1]:,}}}",
            f"\\newcommand{{\\curatedQueries}}{{{le['relabel_curated']['queries'][-1]:,}}}",
            "%% difficulty robustness (results/hard/)",
            f"\\newcommand{{\\hardNone}}{{{df['none'][0]:.2f}}}",
            f"\\newcommand{{\\hardRelabelFinal}}{{{df['relabel'][-1]:.2f}}}",
            f"\\newcommand{{\\hardSelfFinal}}{{{df['success_only'][-1]:.2f}}}",
        ]
    if vision:
        v = vision["strategies"]
        macros += [
            "%% perception-grounded (vision) study",
            f"\\newcommand{{\\visionNoneFinal}}{{{v['none']['success_rate_mean'][-1]:.2f}}}",
            f"\\newcommand{{\\visionRelabelFinal}}{{{v['relabel']['success_rate_mean'][-1]:.2f}}}",
            f"\\newcommand{{\\visionCuratedFinal}}{{{v['relabel_curated']['success_rate_mean'][-1]:.2f}}}",
            f"\\newcommand{{\\visionRelabelGain}}{{{v['relabel']['success_rate_mean'][-1] - v['relabel']['success_rate_mean'][0]:.2f}}}",
            f"\\newcommand{{\\visionCuratedGain}}{{{v['relabel_curated']['success_rate_mean'][-1] - v['relabel_curated']['success_rate_mean'][0]:.2f}}}",
            f"\\newcommand{{\\visionSeeds}}{{{vision['config']['seeds']}}}",
            f"\\newcommand{{\\visionEval}}{{{vision['config']['eval_starts']}}}",
            f"\\newcommand{{\\visionIter}}{{{vision['config']['iterations']}}}",
            f"\\newcommand{{\\visionImg}}{{{vision['config']['img_size']}}}",
        ]
    if dqn:
        fs = strategies.get("relabel", {})
        log = fs.get("curation_log", [])
        fly_inter = log[-1]["dataset_frames"] if log else 0
        macros += [
            "%% DQN from-scratch baseline",
            f"\\newcommand{{\\dqnFinal}}{{{dqn['final_success']:.2f}}}",
            f"\\newcommand{{\\dqnSteps}}{{{dqn['total_env_steps']:,}}}",
            f"\\newcommand{{\\flywheelSteps}}{{{int(fly_inter):,}}}",
        ]
    (out / "numbers.tex").write_text("\n".join(macros) + "\n")

    print(f"wrote {out / 'results_table.tex'} and {out / 'numbers.tex'}")


if __name__ == "__main__":
    main()
