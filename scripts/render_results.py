"""Render paper/generated/results_table.tex + numbers.tex from results/summary.json.

Every number in the manuscript reads from this script's output — never
hand-typed (same convention as our other papers).

Usage: python scripts/render_results.py [--results-dir results] [--out-dir paper/generated]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

STRATEGY_LABELS = {
    "none": "None (frozen)",
    "success_only": "Self: successes",
    "near_miss": "Self: near-misses",
    "success_coverage": "Self: novel successes",
    "relabel": "Oracle: relabel all",
    "relabel_curated": "Oracle: curated relabel",
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", default="results")
    ap.add_argument("--out-dir", default="paper/generated")
    args = ap.parse_args()

    summary = json.loads((Path(args.results_dir) / "summary.json").read_text())
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    strategies = summary["strategies"]
    iters = list(range(summary["config"]["iterations"] + 1))

    # ---- results table -------------------------------------------------- #
    lines = [
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Held-out push success rate (mean $\\pm$ std over "
        f"{summary['config']['seeds']} training seeds, "
        f"{summary['config']['eval_starts']} held-out starts per evaluation) "
        "by curation strategy and flywheel iteration. "
        "Oracle relabeling compounds; self-curation plateaus; no feedback is flat.}",
        "\\label{tab:results}",
        "\\small",
        "\\begin{tabular}{l" + "c" * len(iters) + "}",
        "\\toprule",
        "Strategy & " + " & ".join(f"iter. {i}" for i in iters) + " \\\\",
        "\\midrule",
    ]
    order = ["none", "success_only", "near_miss", "success_coverage",
             "relabel_curated", "relabel"]
    for name in order:
        d = strategies[name]
        cells = " & ".join(
            f"{m:.2f}$\\pm${s:.2f}" for m, s in zip(d["success_rate_mean"], d["success_rate_std"])
        )
        label = STRATEGY_LABELS.get(name, name)
        lines.append(f"{label} & {cells} \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    (out / "results_table.tex").write_text("\n".join(lines) + "\n")

    # ---- number macros --------------------------------------------------- #
    def num(name: str, i: int) -> float:
        return strategies[name]["success_rate_mean"][i]

    def num_std(name: str, i: int) -> float:
        return strategies[name]["success_rate_std"][i]

    base = num("none", 0)
    rel_final = num("relabel", 4)
    cur_final = num("relabel_curated", 4)
    so_final = num("success_only", 4)
    nm_final = num("near_miss", 4)
    sc_final = num("success_coverage", 4)
    rel_gain = rel_final - num("relabel", 0)
    cur_gain = cur_final - num("relabel_curated", 0)
    so_gain = so_final - num("success_only", 0)
    nm_gain = nm_final - num("near_miss", 0)
    cov_gain = sc_final - num("success_coverage", 0)

    macros = [
        "%% AUTO-GENERATED by scripts/render_results.py -- do not edit by hand",
        f"\\newcommand{{\\baseSuccess}}{{{base:.2f}}}",
        f"\\newcommand{{\\relabelFinal}}{{{rel_final:.2f}}}",
        f"\\newcommand{{\\relabelGain}}{{{rel_gain:.2f}}}",
        f"\\newcommand{{\\curatedFinal}}{{{cur_final:.2f}}}",
        f"\\newcommand{{\\curatedGain}}{{{cur_gain:.2f}}}",
        f"\\newcommand{{\\selfFinal}}{{{so_final:.2f}}}",
        f"\\newcommand{{\\selfGain}}{{{so_gain:.2f}}}",
        f"\\newcommand{{\\nearMissFinal}}{{{nm_final:.2f}}}",
        f"\\newcommand{{\\nearMissGain}}{{{nm_gain:.2f}}}",
        f"\\newcommand{{\\coverageFinal}}{{{sc_final:.2f}}}",
        f"\\newcommand{{\\coverageGain}}{{{cov_gain:.2f}}}",
        f"\\newcommand{{\\numSeeds}}{{{summary['config']['seeds']}}}",
        f"\\newcommand{{\\numEval}}{{{summary['config']['eval_starts']}}}",
        f"\\newcommand{{\\numIter}}{{{summary['config']['iterations']}}}",
    ]
    (out / "numbers.tex").write_text("\n".join(macros) + "\n")

    print(f"wrote {out / 'results_table.tex'} and {out / 'numbers.tex'}")


if __name__ == "__main__":
    main()
